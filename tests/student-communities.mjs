import assert from 'node:assert/strict';
import {DemoSocial, emptySocial, validateSocial} from '../web/demo-social.mjs';
import {DraftStore,postIdentity,validatePseudonym} from '../web/student-core.mjs';
import {profileItems} from '../web/discovery-core.mjs';
import {karma,notificationsFor,readablePost} from '../web/engagement-core.mjs';
import {postURL} from '../web/discussion-core.mjs';

const records = new Map();
const storage = {getItem:key=>records.get(key)??null,setItem:(key,value)=>records.set(key,value),removeItem:key=>records.delete(key)};
let time = Date.UTC(2026,10,17,20);
const repo = new DemoSocial({storage:()=>storage,now:()=>time++,lock:task=>task()});
assert.equal(repo.ready,true);
await repo.change('naledi','feed-publish',null,{title:'A fictional confession',text:'Something on my mind.',topic:null,
  anonymous:true,category:'Confessions',circle:'student-confessions'});
const post = repo.data.feedPosts.at(-1);
await repo.change('naledi','feed-comment',post.id,{text:'An update from OP.',parent:null});
const reply = repo.data.feedReplies.at(-1);
assert.equal(postIdentity(post),'Anonymous OP');
assert.equal(postIdentity(post,reply),'Anonymous OP');
assert.equal(postIdentity(post,{author:'sipho'}),null);
assert.equal(profileItems(repo.feed('sipho'),'naledi','Posts').some(p=>p.id===post.id),false);
assert.equal(profileItems(repo.feed('sipho'),'naledi','Replies').some(p=>p.id===reply.id),false);
await repo.change('sipho','feed-vote',post.id);
assert.equal(karma('naledi',repo.feed('sipho')),0);
assert.equal(new URL(postURL('https://example.com',post.id,{actor:'naledi'})).search,'');
assert.equal(notificationsFor(repo.data,'sipho').some(n=>n.from==='naledi'&&n.post===post.id),false);
await repo.change('sipho','feed-report-post',post.id,{reason:'Personal information',details:'Fictional test report'});
await assert.rejects(()=>repo.change('sipho','student-remove',post.id,{kind:'post',reason:'No moderator permission'}));
await repo.change('naledi','student-remove',post.id,{kind:'post',reason:'Contains identifying details'});
assert.equal(readablePost(repo.data,'sipho',post.id),false);
assert.equal(repo.feed('sipho').posts.some(p=>p.id===post.id),false);
await repo.change('naledi','student-restore',post.id,{kind:'post',reason:'Details removed after review'});
assert.equal(readablePost(repo.data,'sipho',post.id),true);
await repo.change('naledi','student-restrict','sipho',{reason:'Repeated harassment'});
await assert.rejects(()=>repo.change('sipho','feed-comment',post.id,{parent:null,text:'Restricted'}));
await repo.change('sipho','student-appeal',null,{text:'Please review this restriction.'});
await assert.rejects(()=>repo.change('sipho','student-appeal',null,{text:'Duplicate appeal'}));
await repo.change('naledi','student-appeal-resolve','sipho',{reason:'Restriction reviewed'});
assert.equal(repo.data.studentAppeals[0].status,'resolved');
assert.equal(repo.data.moderationActions.length,4);

const old = emptySocial(); old.version=9;
for (const key of ['studentRestrictions','moderationActions','studentAppeals','deletedStudents','studentProfiles']) delete old[key];
const original = JSON.stringify(old);
const migrated = validateSocial(old);
assert.equal(migrated.version,10);
assert.equal(JSON.stringify(old),original);
assert.equal(migrated.feedPosts.length,old.feedPosts.length);

const a = new DraftStore('account-a',()=>storage), b = new DraftStore('account-b',()=>storage);
a.write({title:'Private draft'}); assert.equal(b.read(),null); assert.equal(a.read().title,'Private draft');
a.clear(); assert.equal(a.read(),null);
assert.throws(()=>validatePseudonym('A real name'));
await repo.change('ayesha','student-profile',null,{name:'silentstar',avatar:'star'});
assert.equal(repo.data.studentProfiles[0].name,'silentstar');
await repo.change('ayesha','student-delete',null,{confirm:'DELETE'});
await assert.rejects(()=>repo.change('ayesha','feed-comment',post.id,{text:'Deleted account',parent:null}));
assert.ok(repo.data.deletedStudents.includes('ayesha'));
console.log('Student anonymity, profile isolation, moderation, appeals, draft isolation, deletion and migration passed.');
